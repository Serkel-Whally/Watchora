-- Watchora Admin Studio: editorial catalogue and episode management.
create table if not exists public.content_catalogue (
  id bigint generated by default as identity primary key,
  title text not null check (length(title) between 1 and 180),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  kind text not null check (kind in ('Film', 'Series', 'Anime', 'Documentary')),
  description text not null default '' check (length(description) <= 5000),
  release_year integer check (release_year between 1888 and 2200),
  genres text[] not null default '{}',
  country text not null default '',
  original_language text not null default '',
  poster_url text,
  backdrop_url text,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists content_catalogue_status_updated_idx
  on public.content_catalogue(status, updated_at desc);
create index if not exists content_catalogue_kind_idx
  on public.content_catalogue(kind, status);

create table if not exists public.content_episodes (
  id bigint generated by default as identity primary key,
  title_id bigint not null references public.content_catalogue(id) on delete cascade,
  season_number integer not null check (season_number > 0),
  episode_number integer not null check (episode_number > 0),
  title text not null check (length(title) between 1 and 180),
  description text not null default '' check (length(description) <= 3000),
  runtime_minutes integer check (runtime_minutes between 1 and 1000),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(title_id, season_number, episode_number)
);

create index if not exists content_episodes_title_order_idx
  on public.content_episodes(title_id, season_number, episode_number);

alter table public.content_catalogue enable row level security;
alter table public.content_episodes enable row level security;

drop policy if exists "Public can read published catalogue" on public.content_catalogue;
create policy "Public can read published catalogue"
  on public.content_catalogue for select to anon, authenticated
  using (status = 'published');

drop policy if exists "Admins manage catalogue" on public.content_catalogue;
create policy "Admins manage catalogue"
  on public.content_catalogue for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Public can read published episodes" on public.content_episodes;
create policy "Public can read published episodes"
  on public.content_episodes for select to anon, authenticated
  using (
    status = 'published'
    and exists (
      select 1 from public.content_catalogue c
      where c.id = title_id and c.status = 'published'
    )
  );

drop policy if exists "Admins manage episodes" on public.content_episodes;
create policy "Admins manage episodes"
  on public.content_episodes for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

grant select on public.content_catalogue, public.content_episodes to anon, authenticated;
grant insert, update, delete on public.content_catalogue, public.content_episodes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

comment on table public.content_catalogue is
  'Editorial source of truth for Watchora titles. Draft and archived records are admin-only.';
comment on table public.content_episodes is
  'Season and episode metadata attached to a catalogue series.';
